"""Shape سرداب with the bundled OFL Reem Kufi font, then pack a 4-bit mask.

Optional asset regeneration only; normal firmware builds use the checked-in
header. Requires Pillow, fontTools[woff] (Brotli), and HarfBuzz hb-view.
No runtime Unicode/shaping engine or additional device font is required.
"""
import argparse
import hashlib
from pathlib import Path
import shutil
import subprocess
import tempfile
from PIL import Image
from fontTools.ttLib import TTFont
from gen_aa_font import huff_pack, huff_unpack

ROOT = Path(__file__).resolve().parents[1]
TEXT = 'سرداب'
SS = 4


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('output', nargs='?', type=Path, default=ROOT/'firmware/src/sardab_wordmark.h')
    ap.add_argument('--hb-view', default=shutil.which('hb-view'))
    args = ap.parse_args()
    if not args.hb_view:
        ap.error('hb-view is required for optional asset regeneration')
    source = ROOT/'web/fonts/reem-kufi.woff2'
    with tempfile.TemporaryDirectory() as temp:
        temp = Path(temp)
        font = TTFont(source)
        assert all(ord(c) in font.getBestCmap() for c in TEXT), 'Font lacks Persian letters'
        font.flavor = None
        font.save(temp/'font.ttf')
        subprocess.run([args.hb_view, str(temp/'font.ttf'), TEXT, '--direction=rtl',
                        '--language=fa', '--script=arab', '--shapers=ot', '--variations=wght=600',
                        f'--font-size={48*SS}', '--foreground=ffffff', '--background=000000',
                        '--margin=4', f'--output-file={temp / "word.png"}'], check=True)
        mask = Image.open(temp/'word.png').convert('L')
        box = mask.getbbox()
        assert box, 'Empty wordmark'
        mask = mask.crop((box[0], box[1], box[0]+((box[2]-box[0]+SS-1)//SS)*SS,
                          box[1]+((box[3]-box[1]+SS-1)//SS)*SS)).reduce(SS)
        mask = mask.crop(mask.getbbox())
    w, h = mask.size
    assert 50 <= w <= 160 and 16 <= h <= 64, (w, h)
    alpha = [(v*15+127)//255 for v in mask.tobytes()]
    hc, encoded = huff_pack([alpha])
    assert huff_unpack(hc, encoded[0], len(alpha)) == alpha
    compressed = encoded[0] + bytes(2)  # renderer reads ahead
    if len(alpha)%2: alpha.append(0)
    packed = bytes((alpha[i]<<4)|alpha[i+1] for i in range(0,len(alpha),2))
    lines = ['/* SPDX-License-Identifier: OFL-1.1',
             ' * Generated by tools/gen_sardab_wordmark.py; do not hand-edit.',
             ' * سرداب — Reem Kufi, weight 600, 48px; OpenType shaping, RTL, fa.',
             ' * Font licence: LICENSES/OFL-ReemKufi.txt.',
             f' * Source font SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}',
             ' * Huffman-coded 4-bit coverage, using the existing font decoder. */',
             f'#define SARDAB_WORD_W {w}', f'#define SARDAB_WORD_H {h}']
    def array(name, data):
        return [f'static const uint8_t {name}[{len(data)}] = {{'] + [
            '    '+', '.join(f'0x{b:02x}' for b in data[i:i+16])+',' for i in range(0,len(data),16)] + ['};']
    lines += array('SARDAB_WORD_HC', hc) + array('SARDAB_WORD', compressed)
    # Independent uncompressed reference for host pixel checks, excluded from the device.
    lines += ['#if GFX_HOOKS'] + array('SARDAB_WORD_COVERAGE', packed) + ['#endif', '']
    args.output.write_text('\n'.join(lines))
    print(f'Persian splash: {w} x {h}, {len(compressed)+len(hc)} device bytes -> {args.output}')


if __name__ == '__main__':
    main()
